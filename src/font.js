const parsed = new Map();
function glyph(ch) {
  const key = GLYPHS[ch] ? ch : '?';
  if (!parsed.has(key)) parsed.set(key, GLYPHS[key].split(',').map((row) => [...row].map((b) => b === '1')));
  return parsed.get(key);
}

export const CHAR_W = 6; // 5 px glyph + 1 px gap
export const CHAR_H = 7;

export function textWidth(text, scale = 1) {
  return Math.max(0, text.length * CHAR_W * scale - scale);
}

/**
 * Draws upper-case text. `align`: left | center | right. `shadow` draws a 1 px drop shadow.
 */
export function drawText(ctx, text, x, y, color = '#fcfcfc', { align = 'left', scale = 1, shadow = null } = {}) {
  const str = String(text).toUpperCase();
  let left = x;
  if (align === 'center') left = x - Math.floor(textWidth(str, scale) / 2);
  else if (align === 'right') left = x - textWidth(str, scale);
  left = Math.round(left);
  y = Math.round(y);

  const paint = (ox, oy, fill) => {
    ctx.fillStyle = fill;
    for (let i = 0; i < str.length; i++) {
      const rows = glyph(str[i]);
      const gx = left + i * CHAR_W * scale + ox;
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < 5; c++) if (rows[r][c]) ctx.fillRect(gx + c * scale, y + r * scale + oy, scale, scale);
      }
    }
  };
  if (shadow) paint(scale, scale, shadow);
  paint(0, 0, color);
}
